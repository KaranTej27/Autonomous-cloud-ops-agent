// Every detection firing, including ones suppressed as duplicates of an open incident.
export const DETECTIONS: DetectionFiring[] = (() => {
  const r = new Rng(77)
  const out: DetectionFiring[] = []
  for (const inc of INCIDENTS) {
    for (const rule of inc.rule.split(' + ')) {
      out.push({ rule, domain: rule.startsWith('soc') ? 'soc' : 'cloudops', t: inc.createdAt, incidentId: inc.id, suppressed: false })
      const repeats = inc.state === 'resolved' || inc.state === 'closed' ? r.int(0, 2) : r.int(3, 9)
      for (let k = 0; k < repeats; k++) {
        const t = inc.createdAt + r.int(2, 60) * MINUTE
        if (t <= NOW) out.push({ rule, domain: rule.startsWith('soc') ? 'soc' : 'cloudops', t, incidentId: inc.id, suppressed: true })
      }
    }
  }
  // Benign noise that fired but did not open an incident.
  const noise: [string, 'cloudops' | 'soc'][] = [
    ['cloudops.latency_error_rate', 'cloudops'],
    ['soc.failed_logins_then_success', 'soc'],
    ['cloudops.readiness_failures', 'cloudops'],
    ['soc.unexpected_outbound', 'soc'],
  ]
  for (let k = 0; k < 26; k++) {
    const [rule, domain] = r.pick(noise)
    out.push({ rule, domain, t: NOW - r.int(5, 7 * 24 * 60) * MINUTE, suppressed: true })
  }
  return out.sort((a, b) => a.t - b.t)
})()


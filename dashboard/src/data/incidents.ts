function series(n: number, fn: (i: number) => number): number[] {
  return Array.from({ length: n }, (_, i) => Math.max(0, Number(fn(i).toFixed(2))))
}

function ramp(i: number, from: number, to: number, start: number, end: number): number {
  if (i <= start) return from
  if (i >= end) return to
  return from + ((to - from) * (i - start)) / (end - start)
}

